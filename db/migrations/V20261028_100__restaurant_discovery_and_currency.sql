CREATE TABLE feastjourney.restaurant_businesses (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 300),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE feastjourney.restaurant_venues (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  business_id UUID NOT NULL REFERENCES feastjourney.restaurant_businesses(id),
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 300),
  address TEXT NOT NULL CHECK (length(btrim(address)) BETWEEN 1 AND 1000),
  area TEXT NOT NULL CHECK (length(btrim(area)) BETWEEN 1 AND 200),
  country_code TEXT NOT NULL CHECK (country_code ~ '^[A-Z]{2}$'),
  location public.geography(Point,4326) NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (NOT public.ST_IsEmpty(location::public.geometry))
);
CREATE INDEX restaurant_venues_location_idx ON feastjourney.restaurant_venues USING GIST(location);
CREATE INDEX restaurant_venues_bounds_idx ON feastjourney.restaurant_venues USING GIST((location::public.geometry));
CREATE INDEX restaurant_venues_area_idx ON feastjourney.restaurant_venues(lower(area)) WHERE status='published';
CREATE TABLE feastjourney.restaurant_venue_names (
  venue_id UUID NOT NULL REFERENCES feastjourney.restaurant_venues(id),
  language_tag TEXT NOT NULL CHECK (length(language_tag) BETWEEN 2 AND 35),
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 300),
  normalized_name TEXT GENERATED ALWAYS AS (lower(btrim(name))) STORED,
  PRIMARY KEY (venue_id,language_tag,name)
);
CREATE INDEX restaurant_names_trgm_idx ON feastjourney.restaurant_venue_names USING GIN(normalized_name public.gin_trgm_ops);
CREATE INDEX restaurant_names_prefix_idx ON feastjourney.restaurant_venue_names(normalized_name text_pattern_ops);
CREATE TABLE feastjourney.restaurant_venue_cuisines (
  venue_id UUID NOT NULL REFERENCES feastjourney.restaurant_venues(id),
  cuisine_id BIGINT NOT NULL REFERENCES feastjourney.cuisines(id),
  PRIMARY KEY(venue_id,cuisine_id)
);
CREATE TABLE feastjourney.restaurant_menus (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venue_id UUID NOT NULL REFERENCES feastjourney.restaurant_venues(id),
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 300),
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('draft','published','archived')),
  UNIQUE(id,venue_id)
);
CREATE TABLE feastjourney.restaurant_menu_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venue_id UUID NOT NULL,
  menu_id UUID NOT NULL,
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 300),
  description TEXT NOT NULL DEFAULT '' CHECK (length(description)<=3000),
  status TEXT NOT NULL DEFAULT 'published' CHECK (status IN ('draft','published','archived')),
  FOREIGN KEY(menu_id,venue_id) REFERENCES feastjourney.restaurant_menus(id,venue_id),
  UNIQUE(id,venue_id)
);
CREATE TABLE feastjourney.restaurant_menu_item_variants (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venue_id UUID NOT NULL,
  menu_item_id UUID NOT NULL,
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
  comparison_key TEXT CHECK (comparison_key ~ '^[a-z0-9][a-z0-9-]{0,79}$'),
  FOREIGN KEY(menu_item_id,venue_id) REFERENCES feastjourney.restaurant_menu_items(id,venue_id),
  UNIQUE(id,venue_id), UNIQUE(menu_item_id,name)
);
CREATE INDEX restaurant_variants_item_idx ON feastjourney.restaurant_menu_item_variants(menu_item_id);
CREATE TABLE feastjourney.restaurant_sources (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venue_id UUID NOT NULL REFERENCES feastjourney.restaurant_venues(id),
  category TEXT NOT NULL CHECK (category IN ('official_menu','menu_photo','receipt','authorized_provider')),
  source_url TEXT CHECK (source_url ~ '^https?://'),
  private_object_key TEXT CHECK (length(private_object_key) BETWEEN 1 AND 500),
  deduplication_key TEXT NOT NULL CHECK (length(deduplication_key) BETWEEN 1 AND 200),
  restaurant_verified BOOLEAN NOT NULL DEFAULT false,
  eligible BOOLEAN NOT NULL DEFAULT true,
  observed_at TIMESTAMPTZ NOT NULL,
  valid_until TIMESTAMPTZ NOT NULL,
  created_by TEXT NOT NULL REFERENCES feastjourney."user"(id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK(source_url IS NOT NULL OR private_object_key IS NOT NULL),
  CHECK(valid_until > observed_at),
  CHECK(observed_at <= created_at + INTERVAL '5 minutes'),
  CHECK(NOT restaurant_verified OR category IN ('official_menu','authorized_provider')),
  -- Receipt originals must stay private. No public URL or payment/customer fields.
  CHECK(category <> 'receipt' OR source_url IS NULL),
  UNIQUE(venue_id,deduplication_key), UNIQUE(id,venue_id)
);
CREATE TABLE feastjourney.restaurant_serving_evidence (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venue_id UUID NOT NULL,
  menu_item_id UUID NOT NULL,
  dish_id BIGINT NOT NULL REFERENCES feastjourney.dishes(id),
  source_id UUID NOT NULL,
  match_kind TEXT NOT NULL CHECK(match_kind IN ('exact','variant','suggestion')),
  review_status TEXT NOT NULL DEFAULT 'pending' CHECK(review_status IN ('pending','approved','rejected')),
  observed_at TIMESTAMPTZ NOT NULL,
  review_after TIMESTAMPTZ NOT NULL,
  reviewed_by TEXT REFERENCES feastjourney."user"(id),
  reviewed_at TIMESTAMPTZ,
  FOREIGN KEY(menu_item_id,venue_id) REFERENCES feastjourney.restaurant_menu_items(id,venue_id),
  FOREIGN KEY(source_id,venue_id) REFERENCES feastjourney.restaurant_sources(id,venue_id),
  CHECK(review_after > observed_at),
  CHECK(review_status='pending' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  CHECK(review_status<>'approved' OR match_kind<>'suggestion'),
  UNIQUE(menu_item_id,dish_id,source_id)
);
CREATE INDEX restaurant_evidence_dish_idx ON feastjourney.restaurant_serving_evidence(dish_id,venue_id,review_after) WHERE review_status='approved';
CREATE TABLE feastjourney.restaurant_price_observations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  venue_id UUID NOT NULL,
  variant_id UUID NOT NULL,
  source_id UUID NOT NULL,
  source_line_key TEXT NOT NULL CHECK(length(source_line_key) BETWEEN 1 AND 100),
  price_kind TEXT NOT NULL CHECK(price_kind IN ('listed','paid_unit')),
  amount NUMERIC NOT NULL CHECK(amount >= 0 AND amount < 'Infinity'::NUMERIC AND amount <> 'NaN'::NUMERIC),
  currency TEXT NOT NULL REFERENCES feastjourney.currency_codes(code),
  sales_channel TEXT NOT NULL CHECK(sales_channel IN ('dine_in','takeaway','delivery')),
  tax_treatment TEXT NOT NULL CHECK(tax_treatment IN ('included','excluded','unknown')),
  observed_at TIMESTAMPTZ NOT NULL,
  review_after TIMESTAMPTZ NOT NULL,
  review_status TEXT NOT NULL DEFAULT 'pending' CHECK(review_status IN ('pending','approved','rejected')),
  reviewed_by TEXT REFERENCES feastjourney."user"(id),
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY(variant_id,venue_id) REFERENCES feastjourney.restaurant_menu_item_variants(id,venue_id),
  FOREIGN KEY(source_id,venue_id) REFERENCES feastjourney.restaurant_sources(id,venue_id),
  CHECK(review_after > observed_at), CHECK(observed_at<=created_at+INTERVAL '5 minutes'),
  CHECK(review_status='pending' OR (reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)),
  -- One source food line cannot generate several competing observations.
  UNIQUE(source_id,source_line_key)
);
CREATE INDEX restaurant_prices_selection_idx ON feastjourney.restaurant_price_observations(variant_id,sales_channel,observed_at DESC,id) WHERE review_status='approved';

-- Structured private receipt evidence. Never persist full OCR or customer/card data.
CREATE TABLE feastjourney.restaurant_receipt_lines (
  observation_id UUID PRIMARY KEY REFERENCES feastjourney.restaurant_price_observations(id),
  quantity NUMERIC NOT NULL CHECK(quantity>0 AND quantity<'Infinity'::NUMERIC),
  explicit_unit_price NUMERIC CHECK(explicit_unit_price>=0 AND explicit_unit_price<'Infinity'::NUMERIC),
  line_total NUMERIC NOT NULL CHECK(line_total>=0 AND line_total<'Infinity'::NUMERIC),
  discount NUMERIC NOT NULL CHECK(discount>=0 AND discount<'Infinity'::NUMERIC),
  taxes_fees NUMERIC NOT NULL CHECK(taxes_fees>=0 AND taxes_fees<'Infinity'::NUMERIC),
  total_semantics TEXT NOT NULL CHECK(total_semantics IN ('net_food_only','includes_fees','unknown')),
  CHECK(explicit_unit_price IS NOT NULL OR total_semantics='net_food_only')
);
-- Protect observation history and provenance after insertion. Review is a separate mutation.
CREATE FUNCTION feastjourney.restaurant_price_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF (to_jsonb(NEW)-ARRAY['review_status','reviewed_by','reviewed_at']) IS DISTINCT FROM
     (to_jsonb(OLD)-ARRAY['review_status','reviewed_by','reviewed_at']) THEN
    RAISE EXCEPTION 'Price observations are immutable; append a new observation' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER restaurant_price_immutable BEFORE UPDATE ON feastjourney.restaurant_price_observations
FOR EACH ROW EXECUTE FUNCTION feastjourney.restaurant_price_immutable();

CREATE VIEW feastjourney.restaurant_selected_prices AS
SELECT DISTINCT ON(p.variant_id,p.sales_channel)
 p.id AS observation_id,p.variant_id,p.venue_id,p.source_id,p.amount,p.currency,p.price_kind,
 p.sales_channel,p.tax_treatment,p.observed_at,p.review_after,s.category AS source_category,
 CASE WHEN s.category='receipt' THEN NULL ELSE s.source_url END AS source_url,
 (p.review_after>=now() AND s.valid_until>=now()) AS current_enough
FROM feastjourney.restaurant_price_observations p
JOIN feastjourney.restaurant_sources s ON (s.id,s.venue_id)=(p.source_id,p.venue_id)
WHERE p.review_status='approved' AND s.eligible AND p.observed_at<=now() AND s.observed_at<=now()
ORDER BY p.variant_id,p.sales_channel,
 CASE WHEN p.price_kind='listed' THEN 0 ELSE 1 END,
 CASE WHEN p.review_after>=now() AND s.valid_until>=now() THEN 0 ELSE 1 END,
 CASE WHEN s.category='official_menu' AND s.restaurant_verified THEN 0 ELSE 1 END,
 p.observed_at DESC,p.id;

CREATE VIEW feastjourney.restaurant_eligible_evidence AS
SELECT DISTINCT ON(e.menu_item_id,e.dish_id)
 e.id,e.venue_id,e.menu_item_id,e.dish_id,e.match_kind,e.observed_at,e.review_after,
 s.category AS source_category,s.source_url,
 CASE WHEN e.match_kind='exact' THEN 0 ELSE 1 END AS evidence_tier
FROM feastjourney.restaurant_serving_evidence e
JOIN feastjourney.restaurant_sources s ON(s.id,s.venue_id)=(e.source_id,e.venue_id)
WHERE e.review_status='approved' AND e.match_kind IN ('exact','variant') AND s.eligible
 AND e.review_after>=now() AND s.valid_until>=now() AND e.observed_at<=now() AND s.observed_at<=now()
ORDER BY e.menu_item_id,e.dish_id,CASE WHEN e.match_kind='exact' THEN 0 ELSE 1 END,e.observed_at DESC,e.id;

