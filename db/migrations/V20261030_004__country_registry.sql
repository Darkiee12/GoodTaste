-- Source: ISO 3166-1 officially assigned alpha-2 codes (249 total; 9 already
-- seeded by V20261028_002, 240 inserted here) with ISO English short names.
-- Registry key is the alpha-2 code in places.iso3166 (consistent with V004,
-- which removed encyclopedia-coupled identifiers from places).
--
-- Deliberate non-goals (no fabricated geography, no invented dish origins):
-- - display_latitude/longitude are NULL (cartographic placement pending; the
--   display_note says so). Coordinates on this table are map placements only,
--   never origin claims and never restaurant locations.
-- - No place_parents edges for new countries (existing continent/region/city
--   edges are untouched). The descendant CTE in place-find-descendants.sql
--   always includes the country itself, so country-scoped discovery works
--   with zero parents.
-- - No localities, no dish_places links: this migration registers places only.
--
-- Idempotent: every INSERT is guarded by WHERE NOT EXISTS (reruns and
-- overlapping seeds are no-ops). Adds a UNIQUE index on iso3166 so each code
-- resolves deterministically in place-find-by-iso.sql.
-- Expected post-conditions: 249 kind='country' rows, 249 distinct iso3166.

